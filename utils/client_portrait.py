def _fill(tpl: str, **kw) -> str:
    """Подстановка в один проход, НЕ str.format: в данных (ключи, запросы) бывают литеральные фигурные скобки —
    подставленные значения повторно не сканируются, неизвестные {поля} остаются как есть."""
    return re.sub(r"\{([a-z_]+)\}", lambda m: str(kw[m.group(1)]) if m.group(1) in kw else m.group(0), tpl)


_WS = re.compile(r"\s+")


def _clean(s) -> str:
    return _WS.sub(" ", str(s or "").strip())


def _as_list(x) -> list:
    return x if isinstance(x, list) else ([] if x is None else [x])


def data_block(seed: str, region: str, language: str, m: dict) -> str:
    """Блок данных из карты интентов (поля ответа /api/intent-map → map). Терпим к отсутствию любого поля."""
    names = []
    for v in _as_list(m.get("variants")):
        n = _clean(v.get("name") if isinstance(v, dict) else v)
        if n:
            names.append(n)
    glines = []
    for g in _as_list(m.get("groups")):
        if not isinstance(g, dict):
            continue
        macro, sub = _clean(g.get("macro")), _clean(g.get("sub"))
        keys = [_clean(k) for k in _as_list(g.get("keys")) if _clean(k)]
        qs = [_clean(q.get("q") if isinstance(q, dict) else q) for q in _as_list(g.get("queries"))]
        qs = [q for q in qs if q]
        tail = ("ключи: " + "; ".join(keys)) if keys else ("запрос: " + (qs[0] if qs else "нет"))
        glines.append(f"{macro} > {sub} | {_clean(g.get('type')) or 'нет'} | {tail}")
    join = lambda xs: "; ".join(_clean(x) for x in _as_list(xs) if _clean(x)) or "нет"   # noqa: E731
    return _fill(
        DATA_BLOCK, seed=seed, subject=_clean(m.get("subject")) or seed,
        brand="да" if m.get("subject_is_brand") else "нет",
        region=region or "не указан", cities=join(m.get("cities")), language=language or "ru",
        variants="; ".join(names) or "нет", journey=join(m.get("journey")), specifics=join(m.get("specifics")),
        groups="\n".join(glines) or "нет",
    )


def build_prompt(seed: str, region: str, language: str, m: dict) -> str:
    """Промпт Andrew (сид на месте SEED_SLOT) → дописанное → данные. Статичное первым, данные последними."""
    return BASE_PROMPT.replace(SEED_SLOT, seed) + "\n\n" + ADD_PROMPT + "\n\n" + data_block(seed, region, language, m)


# ══════════════════════════ вызов Gemini (без поиска) ══════════════════════════
# "out" — ВСЕ оплачиваемые выходные токены (включая thinking): candidatesTokenCount thinking не содержит → складываем.

async def call_gemini(prompt: str) -> dict:
    t0 = time.perf_counter()
    res = {"text": "", "in": 0, "out": 0, "think": 0}
    err = None
    try:
        key = os.environ["GEMINI_API_KEY"]
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{MODEL}:generateContent?key={key}"
        body: dict = {"contents": [{"role": "user", "parts": [{"text": prompt}]}]}
        if THINKING != "off":
            body["generationConfig"] = {"thinkingConfig": {"thinkingLevel": THINKING}}
        async with httpx.AsyncClient(timeout=HTTP_TIMEOUT) as c:
            r = await c.post(url, json=body)
            r.raise_for_status()
            d = r.json()
        text = "".join(p.get("text", "") for p in d["candidates"][0]["content"].get("parts", []))
        um = d.get("usageMetadata", {})
        think = um.get("thoughtsTokenCount", 0)
        res = {"text": text, "in": um.get("promptTokenCount", 0),
               "out": um.get("candidatesTokenCount", 0) + think, "think": think}
    except Exception as e:  # noqa: BLE001
        err = f"{type(e).__name__}: {e}"
        if "key=" in err:   # URL с ключом попадает в текст httpx-ошибок — в ответ API не отдаём
            err = re.sub(r"key=[^&\s'\"]+", "key=***", err)
    cost = (res["in"] * PRICE[0] + res["out"] * PRICE[1]) / 1_000_000
    res.update({"model": MODEL, "thinking": THINKING, "wall": round(time.perf_counter() - t0, 2),
                "cost": round(cost, 5), "error": err})
    return res


# ══════════════════════════ разбор таблицы ответа ══════════════════════════
_ROW = re.compile(r"^\|\s*\**\s*(\d{1,2})\s*\**\s*\|\s*([^|]*?)\s*\|\s*(.*?)\s*$")
_BR_EDGE = re.compile(r"^(?:\s*<br\s*/?>\s*)+|(?:\s*<br\s*/?>\s*)+$", re.I)


def parse_rows(text: str) -> list[dict]:
    """Строки «| № | Категория | Подробности |» → [{"n", "category", "details"}]; details — как у модели (с <br>, **, *).
    Строка без закрывающей «|» считается незакрытой ячейкой — следующие строки доклеиваются через <br> до закрытия.
    Номер не больше предыдущего = новая таблица; берётся таблица с наибольшим объёмом текста (портрет, не служебная)."""
    tables: list[list[dict]] = [[]]
    open_row = None
    for raw in (text or "").splitlines():
        line = raw.strip()
        if open_row is not None:
            if not line:
                continue
            closed = line.endswith("|")
            open_row["details"] += "<br>" + line.rstrip("|").rstrip()
            if closed:
                open_row = None
            continue
        m = _ROW.match(line)
        if not m:
            continue
        n = int(m.group(1))
        details = m.group(3)
        closed = details.endswith("|")
        row = {"n": n, "category": m.group(2).replace("*", "").strip().strip("[]").strip(),
               "details": details.rstrip("|").rstrip()}
        if tables[-1] and n <= tables[-1][-1]["n"]:
            tables.append([])
        tables[-1].append(row)
        open_row = None if closed else row
    best = max(tables, key=lambda t: sum(len(r["details"]) for r in t))
    for r in best:
        r["details"] = _BR_EDGE.sub("", r["details"])
    return best


