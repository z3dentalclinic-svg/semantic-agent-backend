class PortraitReq(BaseModel):
    seed: str
    region: str = ""
    language: str = ""
    map: dict = {}


async def run_client_portrait(req: PortraitReq) -> dict:
    t0 = time.perf_counter()
    seed = _clean(req.seed)
    region, language = _clean(req.region), _clean(req.language)
    prompt = build_prompt(seed, region, language, req.map or {})
    stage = await call_gemini(prompt)
    text = stage.pop("text")
    rows = parse_rows(text) if not stage["error"] else []
    return {
        "seed": seed, "region": region, "language": language,
        "rows": rows,
        "text": text,            # сырой ответ модели: запасной показ, если таблица не разобрана, и копирование Markdown
        "stage": stage,
        "stats": {"rows": len(rows), "groups_in": len(_as_list((req.map or {}).get("groups"))),
                  "prompt_chars": len(prompt),
                  "total_cost": stage["cost"], "total_wall": round(time.perf_counter() - t0, 2)},
        "build": BUILD,
    }


router = APIRouter()


@router.post("/api/client-portrait")
async def client_portrait_endpoint(req: PortraitReq):
    if not req.seed.strip():
        return JSONResponse({"error": "seed пустой"}, status_code=400)
    if not (req.map or {}).get("groups"):
        return JSONResponse({"error": "map.groups пустой — сначала «Список интентов»"}, status_code=400)
    res = await run_client_portrait(req)
    if res["stage"]["error"] or not res["text"].strip():
        return JSONResponse({"error": res["stage"]["error"] or "модель вернула пустой ответ", "stage": res["stage"],
                             "build": BUILD}, status_code=502)
    return res


